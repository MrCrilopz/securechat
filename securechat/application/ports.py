"""Contratos de repositorio, criptografía y red que los casos de uso reciben inyectados."""
from typing import Protocol

class Repository(Protocol):
    def create_user(self, name: str, password_hash: str, bundle: dict) -> None: ...
    def user(self, name: str) -> dict | None: ...
    def save_hybrid_prekey(self, name: str, record: dict) -> None: ...
    def hybrid_prekey(self, name: str) -> dict | None: ...
    def save_token(self, token: str, name: str, expires: float) -> None: ...
    def token_user(self, token: str, now: float) -> str | None: ...
    def revoke_token(self, token: str) -> None: ...
    def enqueue(self, recipient: str, sender: str, message: dict) -> int: ...
    def inbox(self, recipient: str) -> list: ...
    def acknowledge(self, recipient: str, message_id: int) -> None: ...
    def touch_presence(self, name: str, now: float) -> None: ...
    def clear_presence(self, name: str) -> None: ...
    def contacts(self, name: str, now: float) -> list: ...

class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, encoded: str, password: str) -> bool: ...

class BundleVerifier(Protocol):
    def verify(self, bundle: dict) -> None: ...
    def verify_hybrid(self, record: dict, pinned_bundle: dict) -> None: ...

class Clock(Protocol):
    def __call__(self) -> float: ...

class TokenGenerator(Protocol):
    def __call__(self) -> str: ...

class IdentityFactory(Protocol):
    def restore(self, data: dict): ...

class CryptoProvider(Protocol):
    Identity: IdentityFactory
    def verify_bundle(self, bundle: dict) -> None: ...
    def fingerprint(self, first: dict, second: dict) -> str: ...
    def initiate(self, identity, other: dict) -> tuple: ...
    def accept(self, identity, other: dict, header: dict) -> dict: ...
    def envelope_digest(self, envelope: dict) -> str: ...
    def encrypt(self, state: dict, text: str, content_format: str | None = None) -> dict: ...
    def decrypt(self, state: dict, message: dict) -> str: ...

class ChatGateway(Protocol):
    def bundle(self, name: str) -> dict: ...
    def send(self, recipient: str, envelope: dict) -> dict: ...
    def inbox(self) -> list: ...
    def acknowledge(self, message_id: int) -> dict: ...

class StateWriter(Protocol):
    def __call__(self, state: dict) -> None: ...

class AttachmentPort(Protocol):
    def create(self, name: str, content: bytes) -> str: ...
    def open(self, text: str) -> tuple[str, bytes]: ...

