"""Contrato criptográfico para el laboratorio aislado Double Ratchet."""
from typing import Protocol


class RatchetProvider(Protocol):
    def generate_dh(self) -> bytes: ...
    def dh_public(self, private: bytes) -> bytes: ...
    def dh(self, private: bytes, public: bytes) -> bytes: ...
    def root_step(self, root: bytes, secret: bytes) -> tuple[bytes, bytes]: ...
    def chain_step(self, chain: bytes) -> tuple[bytes, bytes]: ...
    def nonce(self) -> bytes: ...
    def seal(self, key: bytes, nonce: bytes, plaintext: bytes, aad: bytes) -> bytes: ...
    def open(self, key: bytes, nonce: bytes, ciphertext: bytes, aad: bytes) -> bytes: ...
